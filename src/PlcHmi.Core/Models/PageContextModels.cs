namespace 上位机.核心.模型;

/// <summary>
/// 页面上下文寄存器：上位机把"操作员此刻在哪一页、选中了哪个点"同步给 PLC，
/// PLC 程序据此做程序分支或上下料联锁。
///
/// <list type="bullet">
/// <item><b>D10 = 页面号</b>：主监控页写 <c>1</c>，随后按侧栏固定顺序递增
/// （参数设置 2、锁附示教 3……系统设置 11）。页码与身份权限无关——
/// 操作员只看到 4 个导航项时，页码也不能跟着变，否则同一页会有两个号码。</item>
/// <item><b>D651 = 锁附示教点码</b>、<b>D652 = 点胶示教点码</b>：各自页面的点表里选中的点，
/// <b>0 基</b>——第一个点写 <c>0</c>、第二个写 <c>1</c>……
/// <para>两个示教页<b>各有各的点码寄存器</b>（现场口径 2026-10-14）：锁附与点胶的点表互相独立，
/// 共用一个字时后点的那个页面会把另一个的值覆盖掉，PLC 侧分不清当前点属于哪张表。</para></item>
/// <item><b>D653 = 标定其它点点码</b>：标定页「其它点」列表里选中的点，同样 <b>0 基</b>
/// （2026-10-15 现场口径：PLC 据此知道当前操作的是哪个其它点；
/// 这台设备的移动动作由 PLC 程序或动作按钮触发，上位机不再自带「移至指定位置」按钮）。</item>
/// </list>
///
/// <para><b>为什么地址写死在代码里：</b>这几个字是现场约定的固定上下文信号
/// （D10 / D651 / D652 / D653），不属于机种数据、也不参与参数表校验；
/// 写死反而比再开一份配置少一个出错入口。
/// 它们都落在机种区段（D2500–D3999）之外，属"全局记忆"：不随机种切换。</para>
/// </summary>
public static class 页面上下文寄存器
{
    /// <summary>页面号寄存器：D10（主监控 = 1，按侧栏顺序递增）。</summary>
    public const int 页码 = 10;

    /// <summary>锁附示教点码寄存器：D651（0 基，第一个点 = 0）。</summary>
    public const int 锁附示教点码 = 651;

    /// <summary>点胶示教点码寄存器：D652（0 基，第一个点 = 0）。</summary>
    public const int 点胶示教点码 = 652;

    /// <summary>标定页「其它点」点码寄存器：D653（0 基，第一个点 = 0）。</summary>
    public const int 标定其它点点码 = 653;
}
