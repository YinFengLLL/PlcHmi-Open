using 上位机.核心.枚举;

namespace 上位机.通信.汇川;

/// <summary>
/// 汇川软元件规格表（基址 / 序号上限 / 专用功能码）与地址前缀对照表。
///
/// <para><b>为什么单独一个文件：</b>这里全是"数据"——从现场文档抄下来的基址与序号上限，
/// 本身没有逻辑；<see cref="汇川地址解析器"/> 里则全是"算法"。两者混在一个文件里，
/// 既让解析器越过 400 行审查阈值，也让基址表被顺手改错时不容易被看出来。</para>
///
/// <para><b>改动前必读：</b>基址错一个字节，所有数据都会错位。改这里的任何数字之前，
/// 请对照 PLC 文档与 <c>docs/02-参数-示教-机种需求设计.md</c> 的地址规划，
/// 并确认 <see cref="汇川地址解析器.反解"/> 与新表仍然严格互逆 —— 两处必须同改。</para>
/// </summary>
internal static class 汇川软元件规格表
{
    // ── 小型 PLC（EASY 系列 / H5U / H3U）────────────────────────────────
    // 来源：EMQX Neuron 汇川插件文档、factory-builder 帮助平台（两处交叉验证一致）
    public static readonly Dictionary<软元素, 软元素规格> 小型PLC = new()
    {
        // 位元件 —— 线圈区，功能码 01 / 05 / 0F
        [软元素.M] = new(软元素.M, Modbus区域.线圈, 0x0000, 10, 7999),
        [软元素.B] = new(软元素.B, Modbus区域.线圈, 0x3000, 10, 32767),
        [软元素.S] = new(软元素.S, Modbus区域.线圈, 0xE000, 10, 4095),

        // X 是物理输入，Modbus 语义上属于离散输入表（FC02）；Y 是输出，属线圈表（FC01）。
        // 2026-10-17 现场第二次报障后修正：此前把 X 也放进线圈表，等于用 FC01 读输入区——
        // 现场表现正是"Y 一直正确、X 一直对不上"（读到的是同段地址上无关的位）。
        // 兜底仍在：读不到（抛异常）或读全 0 而另一位区有信号时，轮询引擎会切到另一位区
        // （见 PollingEngine.IO.cs），个别把 X 放在线圈表的机型仍能自愈。
        [软元素.X] = new(软元素.X, Modbus区域.离散输入, 0xF800, 8, 1023),   // X0-X1777，八进制
        [软元素.Y] = new(软元素.Y, Modbus区域.线圈, 0xFC00, 8, 1023),   // Y0-Y1777，八进制
        [软元素.特殊寄存器] = new(软元素.特殊寄存器, Modbus区域.线圈, 0x2400, 10, 1023),
        [软元素.T] = new(软元素.T, Modbus区域.线圈, 0xF000, 10, 511),
        [软元素.C] = new(软元素.C, Modbus区域.线圈, 0xF400, 10, 255),

        // 字元件 —— 保持寄存器区，功能码 03 / 06 / 10
        [软元素.D] = new(软元素.D, Modbus区域.保持寄存器, 0x0000, 10, 7999),
        [软元素.R] = new(软元素.R, Modbus区域.保持寄存器, 0x3000, 10, 32767),
        [软元素.系统寄存器] = new(软元素.系统寄存器, Modbus区域.保持寄存器, 0x2400, 10, 1023),
    };

    // ── 中型 PLC（AM600 / AC800，CODESYS 体系）──────────────────────────
    public static readonly Dictionary<软元素, 软元素规格> 中型PLC = new()
    {
        [软元素.Q] = new(软元素.Q, Modbus区域.线圈, 0x0000, 10, 65535),
        [软元素.接口] = new(软元素.接口, Modbus区域.离散输入, 0x0000, 10, 65535),
        [软元素.MW] = new(软元素.MW, Modbus区域.保持寄存器, 0x0000, 10, 65535),

        // 汇川中型 PLC 的 SM / SD 需专用功能码，标准功能码无法访问
        [软元素.特殊寄存器] = new(软元素.特殊寄存器, Modbus区域.线圈, 0x0000, 10, 7999,
            读取功能代码: 0x31, 写入单个功能代码: 0x35, 写入多个功能代码: 0x3F),
        [软元素.系统寄存器] = new(软元素.系统寄存器, Modbus区域.保持寄存器, 0x0000, 10, 7999,
            读取功能代码: 0x33, 写入单个功能代码: 0x36, 写入多个功能代码: 0x40),
    };

    /// <summary>
    /// 地址前缀 → 软元件。
    ///
    /// <para><b>为什么用显式表而不是 <c>Enum.TryParse</c>：</b>前缀是现场约定（<c>"X"/"SM"/"QX"</c>），
    /// 与枚举成员名是两件事。此前靠枚举名去反解前缀，等于把"现场地址写法"绑死在代码标识符上——
    /// 枚举成员一旦改名（哪怕只是换成中文），解析就会静默失配。显式表把两者解耦。</para>
    ///
    /// <para>中型 PLC 的位寻址写作 <c>QX0.3</c> / <c>IX1.0</c>，前缀里的 X 只是"按位"的表示，
    /// 对应枚举为 <see cref="软元素.Q"/> 与 <see cref="软元素.接口"/>。</para>
    /// </summary>
    public static readonly Dictionary<string, 软元素> 前缀对照 = new(StringComparer.OrdinalIgnoreCase)
    {
        ["X"] = 软元素.X,
        ["Y"] = 软元素.Y,
        ["M"] = 软元素.M,
        ["B"] = 软元素.B,
        ["S"] = 软元素.S,
        ["D"] = 软元素.D,
        ["R"] = 软元素.R,
        ["T"] = 软元素.T,
        ["C"] = 软元素.C,
        ["SM"] = 软元素.特殊寄存器,
        ["SD"] = 软元素.系统寄存器,
        ["Q"] = 软元素.Q,
        ["QX"] = 软元素.Q,
        ["I"] = 软元素.接口,
        ["IX"] = 软元素.接口,
        ["MW"] = 软元素.MW,
    };

    /// <summary>按机型取规格表。</summary>
    public static Dictionary<软元素, 软元素规格> 按机型(PLC系列 系列值) =>
        系列值 == PLC系列.小型PLC ? 小型PLC : 中型PLC;
}
