namespace 上位机.通信.仿真;

/// <summary>
/// <see cref="虚拟PLC设备"/> 的「内存映像初始化」部分（partial）。
///
/// <para><b>为什么拆成 partial 文件：</b>主文件（节拍状态机）已接近 400 行规模门禁基线，
/// 软元件布局常量 + 初始内存值是独立的"数据"职责，与状态机逻辑分开后各自可读。</para>
/// </summary>
public sealed partial class 虚拟PLC设备
{
    private void 初始化内存()
    {
        _内存.运行独占(() =>
        {
            // 初始状态：空闲（状态字 0）、安全门常闭触点闭合、料仓有料
            _内存.不安全设置保持寄存器(寄存器D6运行状态, 状态空闲);

            // X2 安全门为常闭触点：门关好时触点闭合 → 原始位为 1
            // （X 是物理输入，写离散输入区 FC02；Y 是输出写线圈区 FC01——与真机口径一致）
            _内存.不安全设置离散输入(X输入基址 + 2, true);

            // X7 急停按钮为常闭触点：未按下时触点闭合 → 原始位为 1
            _内存.不安全设置离散输入(X输入基址 + 7, true);

            _内存.不安全设置保持寄存器(寄存器D200轴目标, 120);

            // 六轴当前位置：Float32 全 0
            设置浮点(寄存器轴X位置, 0f);
            设置浮点(寄存器轴Y位置, 0f);
            设置浮点(寄存器轴Z位置, 0f);
            设置浮点(寄存器轴ZZ位置, 0f);
            设置浮点(寄存器轴GlueZ位置, 0f);
            设置浮点(寄存器轴GlueX位置, 0f);
            设置浮点(寄存器轴R位置, 0f);

            设置UInt32(寄存器D1100周期时间, 0);
            设置UInt32(寄存器D1102输出数量, 0);
            设置UInt32(寄存器D1104目标产量, 5000);
            设置UInt32(寄存器D1106良品数量, 0);
            设置UInt32(寄存器D1108不良品数量, 0);

            // 示教点表区 D2500–D3299 保持全 0（未示教），让上位机读取时能识别为空点

            // 参数区：写入一组现场生效值（与 config/parameters.json 的当前参数一致），
            // 每项 Float32 占 2 字、字序 CDAB（低字在前）。
            设置浮点(寄存器X定位速度, 80.00f);      // D1400 锁附 X 轴定位速度
            设置浮点(寄存器Y定位速度, 100.00f);     // D1402 锁附 Y 轴定位速度
            设置浮点(寄存器Z定位速度, 50.00f);      // D1404 锁附 Z 轴定位速度
            设置浮点(寄存器ZZ定位速度, 10.00f);     // D1406 锁附 ZZ 轴定位速度
            设置浮点(寄存器GlueZ定位速度, 50.00f);  // D1408 点胶 Z 轴定位速度
            设置浮点(寄存器GlueX定位速度, 60.00f);  // D1410 点胶 X 轴定位速度

            // 机种控制区
            _内存.不安全设置保持寄存器(寄存器配方号, 1);
            _内存.不安全设置保持寄存器(寄存器配方数量, 20);
            _内存.不安全设置保持寄存器(寄存器示教序号, 0);
            _内存.不安全设置保持寄存器(寄存器示教面, 0);

            // 面启用标志：全部停用（与需求一致 —— 默认不开启，开启的面才写入）
            for (var 面 = 0; 面 < 寄存器面数量; 面++)
            {
                _内存.不安全设置保持寄存器(寄存器面启用基址 + 面, 0);
            }
        });
    }
}
