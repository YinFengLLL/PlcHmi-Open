using 上位机.核心.模型;

namespace 上位机.上位机测试;

/// <summary>
/// 点胶示教指令码表（2026-10-21 现场口径：PLC 指令表 0 结束 / 1 起点 / 2 直线 … 9 对针）。
///
/// <para>钉死两件事：<b>码值顺序</b>（写进 D3400 段的就是这个数，错一位现场动作就完全不同）
/// 与<b>文字映射</b>（点表「指令码」列显示的文字）。</para>
/// </summary>
public class 指令码定义测试
{
    [Fact]
    public void 指令码表应与PLC指令表一致()
    {
        var 期望 = new[]
        {
            (码: 0, 名称: "结束"),
            (码: 1, 名称: "起点"),
            (码: 2, 名称: "直线"),
            (码: 3, 名称: "直线终点"),
            (码: 4, 名称: "圆弧中点"),
            (码: 5, 名称: "圆弧终点"),
            (码: 6, 名称: "单点"),
            (码: 7, 名称: "空移"),
            (码: 8, 名称: "刮胶"),
            (码: 9, 名称: "对针"),
        };

        Assert.Equal(期望.Length, 指令码定义.全部.Count);

        for (var 索引 = 0; 索引 < 期望.Length; 索引++)
        {
            var 项 = 指令码定义.全部[索引];
            Assert.Equal(期望[索引].码, 项.码);
            Assert.Equal(期望[索引].名称, 项.名称);
            Assert.Equal($"{期望[索引].码:00} - {期望[索引].名称}", 项.显示);
        }
    }

    [Theory]
    [InlineData(0, "结束")]
    [InlineData(2, "直线")]
    [InlineData(9, "对针")]
    public void 码值应显示为对应文字(int 码, string 文字) =>
        Assert.Equal(文字, 指令码定义.显示文本(码));

    [Fact]
    public void 未知码值应原样显示数字()
    {
        // 老机种里可能存着按旧口径手填的值（例如 100），显示原值才能与 PLC 对照
        Assert.Equal("100", 指令码定义.显示文本(100));
        Assert.Null(指令码定义.查找(10));
        Assert.Null(指令码定义.查找(-1));
    }
}
