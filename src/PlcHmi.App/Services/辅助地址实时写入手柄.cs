using Microsoft.Extensions.Logging;
using 上位机.应用.视图模型;
using 上位机.核心.抽象;
using 上位机.核心.模型;

namespace 上位机.应用.服务;

/// <summary>
/// 辅助地址「实时读写」的统一实现（2026-11-12 现场要求，锁附示教 / 点胶示教 / 标定页共用）。
///
/// <para><b>两条规矩：</b></para>
/// <list type="number">
///   <item>页面上看到的值就是 PLC 现值——页面停留期间跟随周期回读（由各页把
///   <see cref="异步刷新值"/> 挂在 2s 回读节拍里），不再需要按「读取」；</item>
///   <item>改完就生效——输入框回车 / 失焦、勾选框变化即写 PLC，不再有「写入」按钮。</item>
/// </list>
///
/// <para><b>写入门槛是手动使能</b>：辅助地址是工艺参数，随手改一个数就可能是撞机 / 撞针。
/// 未使能时行置灰、真要写也会被这里拦下并把界面拉回 PLC 真实值。</para>
/// </summary>
public sealed class 辅助地址实时写入手柄
{
    private readonly ILogger _日志;
    private readonly 对话框服务接口 _对话框;
    private readonly Func<bool> _允许写入;

    public 辅助地址实时写入手柄(ILogger 日志, 对话框服务接口 对话框, Func<bool> 允许写入)
    {
        _日志 = 日志;
        _对话框 = 对话框;
        _允许写入 = 允许写入;
    }

    /// <summary>按配置创建一行（构造与改地址后重建走同一条路，不会出现"重建出来的行改不了"）。</summary>
    public 辅助地址行视图模型 创建(辅助地址项 项, 页面地址服务接口 服务)
    {
        ArgumentNullException.ThrowIfNull(项);
        ArgumentNullException.ThrowIfNull(服务);

        return new 辅助地址行视图模型(项, 服务)
        {
            可编辑 = _允许写入(),
            提交请求 = 提交,
        };
    }

    /// <summary>手动使能变化后同步各行的可编辑状态。</summary>
    public void 刷新可编辑(IEnumerable<辅助地址行视图模型> 行集合)
    {
        foreach (var 行项 in 行集合)
        {
            行项.可编辑 = _允许写入();
        }
    }

    /// <summary>
    /// 周期回读各行的显示值。
    /// <para><b>跳过正在输入的行</b>：否则操作员输到一半，PLC 的旧值会把输入框覆盖掉。
    /// 单项容错：某行地址配错 / 读失败只跳过它，不打断整页的周期回读。</para>
    /// </summary>
    public Task 异步刷新值(IEnumerable<辅助地址行视图模型> 行集合) =>
        // 2026-11-19 性能改造：一行一个 Modbus 请求 → 连续地址合并成 2~4 个请求。
        // 批量实现仍然逐行跳过"正在输入"的行、单项容错，语义与逐行读一致；
        // 上限提到 30 行后这是保住快组 100ms 采集周期的关键。
        辅助地址行视图模型.异步批量刷新(行集合 as IReadOnlyList<辅助地址行视图模型> ?? 行集合.ToList());

    private void 提交(辅助地址行视图模型 行项)
    {
        if (!_允许写入())
        {
            _对话框.提示("需要手动使能",
                $"修改「{行项.名称}」的当前值前，请先打开手动使能。");

            // 界面上这半截改动不能留着：看着像改成功了，PLC 里其实没变
            异步安全调用.即发即忘(行项.异步刷新显示, _日志, $"回读辅助地址「{行项.名称}」");
            return;
        }

        异步安全调用.即发即忘(
            () => 异步写入核心(行项),
            _日志,
            $"写入辅助地址「{行项.名称}」");
    }

    private async Task 异步写入核心(辅助地址行视图模型 行项)
    {
        Func<Task> 命令 = 行项.是开关 ? 行项.异步写入开关 : 行项.异步写入;

        if (await 界面命令
                .异步执行(_日志, _对话框, $"写入「{行项.名称}」", 命令)
                .ConfigureAwait(true))
        {
            _日志.LogInformation("辅助地址「{Name}」（{Address}）已实时写入 PLC",
                行项.名称, 行项.地址文本);
            return;
        }

        // 失败（数字非法 / 通信异常 / 权限不足）：界面拉回 PLC 的真实值
        异步安全调用.即发即忘(行项.异步刷新显示, _日志, $"回读辅助地址「{行项.名称}」");
    }
}
