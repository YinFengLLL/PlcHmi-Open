using Microsoft.Extensions.Logging;
using 上位机.核心.枚举;
using 上位机.核心.模型;

namespace 上位机.业务.服务;

/// <summary>
/// 轮询引擎的「读取计划编译」部分（partial）。
///
/// <para><b>为什么拆成 partial 文件：</b>采集计划编排 + 分组调度 + 实际解码发布 + 计划编译
/// 四件事合在一个文件里已超过 400 行规模门禁。计划编译是独立的纯函数式职责
/// （地址解析 → 合并 → 分块），单独成文件后每个文件只讲一件事。</para>
/// </summary>
public sealed partial class 轮询引擎
{
    /// <summary>
    /// 把点位列表编译为“读取计划”：合并连续地址，按最大寄存器数分块。
    /// </summary>
    private List<读取方案> 构建读取方案列表(IReadOnlyList<标签定义> 标签列表)
    {
        // 单次请求上限与通信层共用同一个配置项（appsettings.json 的 Plc.MaxRegistersPerRequest），
        // 不再各处硬编码：两处各写一个数，改一处漏一处就会超出汇川的读 123 上限。
        // 原先这里是 `FastIntervalMs > 0 ? 100 : 100`——两个分支同值，是死代码。
        var 最大寄存器 = _PLC选项.每次请求最大寄存器数;
        var 方案列表 = new List<读取方案>();

        // 位元件与字元件分开处理，且各自按 Modbus 区域分组：
        // 中型 PLC 的 IX 位元件位于离散输入区，必须走 FC02；
        // 此前按"线圈 / 保持寄存器"二分，离散输入区与输入寄存器区的点
        // 会被套上错误的读取区域（异步轮询标签 里的分支沦为死代码）。
        // D/R 字内位（如 D1210.2，布尔但落在保持寄存器区）按 1 字寄存器读取，发布时按位取值。
        var 位标签 = new List<(标签定义 标签, int 地址, Modbus区域 区域)>();
        var 寄存器标签 = new List<(标签定义 标签, int 地址, int 数量, int 位序号, Modbus区域 区域)>();

        // 机种区段（D2500–D3999）里的数据不自动回读（2026-10-21 现场要求）：
        // 这一段是点表 / 单点工艺参数 / 机种快照的落点，改为"示教页按「读取点表」按需读取"。
        // 周期采集这段既没必要（每秒几百字），也会让人误以为界面在实时跟随 PLC。
        var 跳过机种区段 = 0;

        foreach (var 标签项 in 标签列表)
        {
            if (!标签项.可读取 || !_解析器.尝试解析(标签项.地址, out var 地址值) || 地址值 is null)
            {
                if (标签项.可读取)
                {
                    _日志.LogWarning("点位 {Name} 地址 \"{Address}\" 无法解析，已跳过", 标签项.名称, 标签项.地址);
                }

                continue;
            }

            if (地址值.区域 is Modbus区域.保持寄存器 && 机种区段.包含(地址值.Modbus地址))
            {
                跳过机种区段++;
                continue;
            }

            var 寄存器数量项 = _解析器.获取寄存器数量(标签项.数据类型);

            if (地址值.区域 is Modbus区域.线圈 or Modbus区域.离散输入
                && 标签项.数据类型 == 标签数据类型.布尔)
            {
                位标签.Add((标签项, 地址值.Modbus地址, 地址值.区域));
            }
            else
            {
                // 布尔字内位恒占 1 字（整字读），不能用类型的寄存器数量
                var 是位标签 = 地址值.是字内位 && 标签项.数据类型 == 标签数据类型.布尔;
                寄存器标签.Add((标签项, 地址值.Modbus地址,
                    是位标签 ? 1 : 寄存器数量项,
                    是位标签 ? 地址值.位序号 : -1,
                    地址值.区域));
            }
        }

        // 位元件：按区域分组，连续地址合并为一次读位请求（线圈 / 离散输入）
        // 合并上限用 Modbus 位上限（FC01/FC02 = 2000 位），不是字上限（100）——
        // 曾误用寄存器上限，1000 个 M 区布尔点被拆成 10 次请求，白白多出 9 次往返
        foreach (var 区域组 in 位标签.GroupBy(位项 => 位项.区域))
        {
            foreach (var 数据块 in 合并地址(区域组.Select(位项 => 位项.地址), 每次请求最大线圈数))
            {
                var 成员列表 = 区域组
                    .Where(位项 => 位项.地址 >= 数据块.启动 && 位项.地址 < 数据块.启动 + 数据块.数量)
                    .Select(位项 => new 方案成员(位项.标签, 位项.地址 - 数据块.启动, 1))
                    .ToList();

                方案列表.Add(new 读取方案(区域组.Key, 数据块.启动, 数据块.数量, 成员列表));
            }
        }

        if (跳过机种区段 > 0)
        {
            _日志.LogInformation(
                "机种区段 D{Start}–D{End} 不做周期采集（{Count} 个点位已跳过），点表由示教页「读取点表」按需读取",
                机种区段.起始, 机种区段.结束, 跳过机种区段);
        }

        // 字元件：按区域分组，各自按起始与结束地址合并（保持 / 输入寄存器）
        foreach (var 区域组 in 寄存器标签.GroupBy(寄存器项 => 寄存器项.区域))
        {
            var 有序 = 区域组.OrderBy(寄存器项 => 寄存器项.地址).ToList();
            var 序号 = 0;

            while (序号 < 有序.Count)
            {
                var 启动 = 有序[序号].地址;
                var 结束 = 有序[序号].地址 + 有序[序号].数量;
                var 成员列表 = new List<方案成员> { new(有序[序号].标签, 0, 有序[序号].数量, 有序[序号].位序号) };
                序号++;

                while (序号 < 有序.Count)
                {
                    var 下一个 = 有序[序号];
                    var 投影结束 = Math.Max(结束, 下一个.地址 + 下一个.数量);

                    // 超过单次上限就断开
                    if (投影结束 - 启动 > 最大寄存器)
                    {
                        break;
                    }

                    // 允许与当前区间重叠或紧邻（无空洞）
                    if (下一个.地址 > 结束)
                    {
                        break;
                    }

                    成员列表.Add(new 方案成员(下一个.标签, 下一个.地址 - 启动, 下一个.数量, 下一个.位序号));
                    结束 = 投影结束;
                    序号++;
                }

                方案列表.Add(new 读取方案(区域组.Key, 启动, 结束 - 启动, 成员列表));
            }
        }

        return 方案列表;
    }

    /// <summary>把一组地址合并为连续区间（按最大值切块）。</summary>
    private static IEnumerable<(int 启动, int 数量)> 合并地址(IEnumerable<int> 地址列表, int 最大长度)
    {
        // SortedSet 一趟完成排序 + 去重（原 Distinct().OrderBy().ToList() 三趟遍历）
        var 有序 = new SortedSet<int>(地址列表).ToList();
        var 序号 = 0;

        while (序号 < 有序.Count)
        {
            var 启动 = 有序[序号];
            var 结束 = 启动 + 1;
            序号++;

            while (序号 < 有序.Count && 有序[序号] <= 结束 && 有序[序号] - 启动 < 最大长度)
            {
                结束 = Math.Max(结束, 有序[序号] + 1);
                序号++;
            }

            yield return (启动, Math.Min(结束 - 启动, 最大长度));
        }
    }

    // ── 内部类型 ────────────────────────────────────────────────────────

    /// <summary>
    /// 读取方案里的一个点位成员。
    /// <para><paramref name="位序号"/> ≥ 0 表示 D/R 区字内位（布尔）：
    /// 读取仍是整字，发布时按 <c>(字值 &gt;&gt; 位) &amp; 1</c> 取布尔值。</para>
    /// </summary>
    private sealed record 方案成员(标签定义 标签, int 偏移, int 寄存器数量, int 位序号 = -1);

    private sealed record 读取方案(Modbus区域 区域, int 启动地址, int 数量, List<方案成员> 成员集合);

    private sealed record 轮询分组(标签分组 分组, TimeSpan 间隔, List<读取方案> 方案集合, bool 含IO);
}
