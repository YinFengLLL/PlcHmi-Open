using 上位机.核心.枚举;
using 上位机.核心.模型;

namespace 上位机.业务.服务;

/// <summary>
/// <see cref="页面地址服务"/> 的「收集标定页」部分（partial）。
///
/// <para>从主文件拆出：主文件逼近 400 行规模门禁。这里只做"把标定页的所有元件地址
/// 摊成一份可编辑清单"，不碰读写与落盘。</para>
/// </summary>
public sealed partial class 页面地址服务
{
    /// <summary>说明：标定页复用锁附 X/Y/Z 三根轴（点动与回零）。</summary>
    private static readonly string[] 标定轴 = ["X", "Y", "Z"];

    /// <inheritdoc />
    public IReadOnlyList<地址编辑项> 收集标定页()
    {
        var 列表 = new List<地址编辑项>();

        foreach (var 字段项 in _配置.标定.中心点)
        {
            列表.Add(new 地址编辑项
            {
                类别 = "标定字段",
                键 = 字段项.键,
                名称 = 字段项.显示名称,
                地址文本 = $"D{字段项.基址}",
                数据类型文本 = 字段项.数据类型.ToString(),
            });
        }

        var 偏移 = _配置.标定.每点偏移;
        列表.Add(new 地址编辑项
        {
            类别 = "标定字段",
            键 = 偏移.键,
            名称 = 偏移.显示名称,
            地址文本 = $"D{偏移.基址}",
            数据类型文本 = 偏移.数据类型.ToString(),
        });

        列表.Add(new 地址编辑项
        {
            类别 = "标定按钮",
            键 = "启动",
            名称 = "上相机标定启动",
            地址文本 = _配置.标定.启动地址,
            数据类型文本 = 标签数据类型.布尔.ToString(),
        });

        // 下相机（2026-10-17 新增）：地址处理模式与上相机一致，但**没有 Y**，只有 X / Z。
        // 键加「下相机」前缀：上相机已占用 X / Y / Z / 偏移量 这几个键，
        // 编辑器的行是按「类别 + 键」定位的，重键会把两套地址写串。
        var 已收下相机键 = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var 字段项 in _配置.标定.下相机中心点)
        {
            已收下相机键.Add(字段项.键);
            列表.Add(new 地址编辑项
            {
                类别 = "标定字段",
                键 = $"下相机{字段项.键}",
                名称 = 字段项.显示名称,
                地址文本 = $"D{字段项.基址}",
                数据类型文本 = 字段项.数据类型.ToString(),
            });
        }

        // 老现场配置没有下相机字段时，编辑器必须照样给出 X / Z 两行：
        // 否则管理员根本看不到、也改不了地址，下发只会报"缺少该字段"（2026-10-21 现场报障）。
        // 这里只合成显示行，保存时由 应用标定字段 把字段补进配置。
        foreach (var 缺省 in 标定配置.下相机缺省中心点())
        {
            if (!已收下相机键.Add(缺省.键))
            {
                continue;
            }

            列表.Add(new 地址编辑项
            {
                类别 = "标定字段",
                键 = $"下相机{缺省.键}",
                名称 = 缺省.显示名称,
                地址文本 = $"D{缺省.基址}",
                数据类型文本 = 缺省.数据类型.ToString(),
            });
        }

        var 下相机偏移 = _配置.标定.下相机每点偏移;
        var 偏移基址 = 下相机偏移.基址 > 0 ? 下相机偏移.基址 : 标定配置.下相机偏移缺省基址;

        列表.Add(new 地址编辑项
        {
            类别 = "标定字段",
            键 = "下相机偏移量",
            名称 = 下相机偏移.显示名称,
            地址文本 = $"D{偏移基址}",
            数据类型文本 = 下相机偏移.数据类型.ToString(),
        });

        列表.Add(new 地址编辑项
        {
            类别 = "标定按钮",
            键 = "下相机启动",
            名称 = "下相机标定启动",
            地址文本 = _配置.标定.下相机启动地址,
            数据类型文本 = 标签数据类型.布尔.ToString(),
        });

        // 「移至指定位置」已按现场要求删除（2026-10-15）：与锁附分组动作按钮「移全指定」
        // 是同一个 M460，重复；要改这个地址请走「标定」分组的动作按钮条目。

        foreach (var 轴号 in 标定轴)
        {
            if (查找点动(轴号, "锁附") is not { } 点动项)
            {
                continue;
            }

            列表.Add(new 地址编辑项
            {
                类别 = "点动",
                键 = $"{点动项.轴}|正转",
                名称 = $"{点动项.显示名称}·正转",
                地址文本 = 点动项.正转地址,
                数据类型文本 = 标签数据类型.布尔.ToString(),
            });

            列表.Add(new 地址编辑项
            {
                类别 = "点动",
                键 = $"{点动项.轴}|反转",
                名称 = $"{点动项.显示名称}·反转",
                地址文本 = 点动项.反转地址,
                数据类型文本 = 标签数据类型.布尔.ToString(),
            });

            列表.Add(new 地址编辑项
            {
                类别 = "回零",
                键 = 点动项.轴,
                名称 = $"{点动项.显示名称}·回零",
                地址文本 = 查找回零(点动项.轴)?.地址 ?? string.Empty,
                数据类型文本 = 标签数据类型.布尔.ToString(),
            });
        }

        // 标定页采用与锁附页相同的元件配置方式：动作按钮 / 辅助地址按「标定」分组纳入，
        // 管理员可新增、改名、改址与删除（当前默认配置里为空，故页面上看不到条目）。
        foreach (var 项 in _配置.动作按钮.Where(项 => 分组匹配(项.分组, "标定")))
        {
            列表.Add(new 地址编辑项
            {
                类别 = "动作按钮",
                键 = 项.键,
                名称 = 项.显示名称,
                地址文本 = 项.地址,
                数据类型文本 = 标签数据类型.布尔.ToString(),
                分组 = 项.分组,
                可删除 = true,
            });
        }

        foreach (var 项 in _配置.辅助地址.Where(项 => 分组匹配(项.分组, "标定")))
        {
            列表.Add(new 地址编辑项
            {
                类别 = "辅助地址",
                键 = 项.键,
                名称 = 项.显示名称,
                地址文本 = 项.地址,
                数据类型文本 = 项.数据类型.ToString(),
                分组 = 项.分组,
                可删除 = true,
            });
        }

        return 列表;
    }
}
